// Lesson 09: sqlc, compile-time checked SQL.
//
// sqlc flips the usual ORM idea: YOU write plain SQL in query.sql, and sqlc GENERATES the Go
// code (structs, params, methods) by reading your schema and queries.
//
//	sqlc.yaml  +  ../sql/schema.sql  +  query.sql   ->   `go tool sqlc generate`   ->   db/*.go
//
// What you get:
//   - Compile-time safety: a wrong column or table name fails at GENERATE time, and a changed
//     column type breaks the Go build instead of production.
//   - No hand-written Scan code, no reflection at runtime, and no performance cost over
//     database/sql: the generated methods call database/sql directly.
//   - Query annotations choose the Go signature:
//     :one -> (T, error)   :many -> ([]T, error)   :exec -> error   :execrows -> (int64, error)
//   - sqlc.narg('x') makes a parameter nullable so you can write optional filters.
//   - db.New(sqlDB) works with *sql.DB or *sql.Tx (anything implementing DBTX), and
//     q.WithTx(tx) rebinds the same Queries to a transaction.
//
// Workflow:
//  1. edit schema.sql (or migrations) and query.sql
//  2. run `make sqlc` (this repo pins sqlc as a Go tool: `go tool sqlc generate -f ...`)
//  3. COMMIT the generated db/ folder: builds should not need sqlc installed, and diffs show
//     exactly how a query change altered the code.
//
// Gotchas:
//   - Never edit generated files; change the SQL and regenerate.
//   - SQLite is loosely typed, so sqlc maps every INTEGER to int64 and nullable columns to
//     sql.NullString / sql.NullInt64. PostgreSQL gives richer types (and pgx integration).
//   - Dynamic queries (optional filters, variable column lists) are sqlc's weak spot. The
//     sqlc.narg pattern below covers filters; for truly dynamic SQL use a query builder.
//
// In industry: sqlc is very popular for Go services that want raw-SQL control with type safety.
// Typical layout: one sqlc.yaml per service, queries grouped by table in several .sql files,
// generated package named `db` or `sqlcgen`, wrapped by a thin repository/store layer.
package main

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
	"log"

	"github.com/vidyesh95/Go-Tutorial/03-sql-sqlite/09sqlc/db"
	"github.com/vidyesh95/Go-Tutorial/03-sql-sqlite/internal/sqldb"
)

func main() {
	ctx := context.Background()
	sqlDB, cleanup, err := sqldb.OpenTemp(ctx)
	if err != nil {
		log.Fatal(err)
	}
	defer cleanup()

	q := db.New(sqlDB) // one Queries value; safe for concurrent use

	fmt.Println("== GetTask (:one) ==")
	t, err := q.GetTask(ctx, 2)
	if err != nil {
		log.Fatal(err)
	}
	fmt.Printf("%+v\n", t)

	_, err = q.GetTask(ctx, 9999)
	fmt.Println("missing task -> sql.ErrNoRows:", errors.Is(err, sql.ErrNoRows))

	fmt.Println("\n== ListTasksByProject (:many) ==")
	tasks, err := q.ListTasksByProject(ctx, 2)
	if err != nil {
		log.Fatal(err)
	}
	for _, t := range tasks {
		fmt.Printf("  #%-2d %-24s %-5s p%d\n", t.ID, t.Title, t.Status, t.Priority)
	}

	fmt.Println("\n== CreateTask (:one with RETURNING *) ==")
	created, err := q.CreateTask(ctx, db.CreateTaskParams{
		ProjectID:  1,
		AssigneeID: sql.NullInt64{Int64: 4, Valid: true}, // assign to Dara
		Title:      "Generated by sqlc",
		Status:     "todo",
		Priority:   2,
		DueDate:    sql.NullString{}, // NULL
	})
	if err != nil {
		log.Fatal(err)
	}
	fmt.Printf("created id=%d title=%q created_at=%s\n", created.ID, created.Title, created.CreatedAt)

	fmt.Println("\n== UpdateTaskStatus (:exec) ==")
	err = q.UpdateTaskStatus(ctx, db.UpdateTaskStatusParams{Status: "doing", ID: created.ID})
	fmt.Println("err:", err)

	fmt.Println("\n== ListTasksFiltered (sqlc.narg optional filters) ==")
	show := func(label string, p db.ListTasksFilteredParams) {
		rows, err := q.ListTasksFiltered(ctx, p)
		if err != nil {
			log.Fatal(err)
		}
		fmt.Printf("  %-28s -> %d rows:", label, len(rows))
		for _, r := range rows {
			fmt.Printf(" #%d", r.ID)
		}
		fmt.Println()
	}
	show("no filters, limit 5", db.ListTasksFilteredParams{RowLimit: 5})
	show("status=doing", db.ListTasksFilteredParams{Status: sql.NullString{String: "doing", Valid: true}, RowLimit: 50})
	show("assignee=2", db.ListTasksFilteredParams{AssigneeID: sql.NullInt64{Int64: 2, Valid: true}, RowLimit: 50})
	show("status=todo AND assignee=2", db.ListTasksFilteredParams{
		Status:     sql.NullString{String: "todo", Valid: true},
		AssigneeID: sql.NullInt64{Int64: 2, Valid: true},
		RowLimit:   50,
	})

	fmt.Println("\n== CountTasksByStatus (:many, custom row type) ==")
	counts, err := q.CountTasksByStatus(ctx, 1)
	if err != nil {
		log.Fatal(err)
	}
	for _, c := range counts {
		fmt.Printf("  %-6s %d\n", c.Status, c.Total)
	}

	fmt.Println("\n== ListProjectsWithTaskCount (join, generated row struct) ==")
	projects, err := q.ListProjectsWithTaskCount(ctx)
	if err != nil {
		log.Fatal(err)
	}
	for _, p := range projects {
		fmt.Printf("  %-18s owner=%-5s tasks=%d\n", p.Name, p.OwnerName, p.TaskCount)
	}

	fmt.Println("\n== WithTx: the same generated methods inside a transaction ==")
	tx, err := sqlDB.BeginTx(ctx, nil)
	if err != nil {
		log.Fatal(err)
	}
	defer tx.Rollback()
	qtx := q.WithTx(tx)
	n, err := qtx.DeleteTask(ctx, created.ID) // :execrows returns rows affected
	fmt.Println("deleted inside tx:", n, err)
	if err := tx.Rollback(); err != nil { // change our mind
		log.Fatal(err)
	}
	_, err = q.GetTask(ctx, created.ID)
	fmt.Println("after rollback the task still exists:", err == nil)

	n, err = q.DeleteTask(ctx, created.ID) // now delete for real
	fmt.Println("deleted for real:", n, err)
	n, _ = q.DeleteTask(ctx, created.ID)
	fmt.Println("deleting again affects:", n, "rows")
}
